export function categoryJsonLd(category: string, label: string, seo: CategorySeo) {
  const url = `${SITE_URL}/opportunities/${category}`;
  return [
    {
      '@context': 'https://schema.org',
      '@type': 'CollectionPage',
      name: seo.title,
      description: seo.description,
      url,
      inLanguage: 'ru',
      isPartOf: { '@type': 'WebSite', name: 'Teenage Space', url: `${SITE_URL}/` },
      about: label
    },
    {
      '@context': 'https://schema.org',
      '@type': 'BreadcrumbList',
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'Teenage Space', item: `${SITE_URL}/` },
        { '@type': 'ListItem', position: 2, name: 'Возможности', item: `${SITE_URL}/opportunities` },
        { '@type': 'ListItem', position: 3, name: label, item: url }
      ]
    }
  ];
}
