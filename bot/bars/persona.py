GREETING = """Привет! Я Барс — помогаю находить мероприятия в Бишкеке и готовиться к ним.

Расскажи, что тебе интересно и сколько тебе лет — подберу подходящее. А ещё могу составить план подготовки и напомнить о дедлайне."""

HELP_TEXT = """Вот что я умею:

• Просто напиши, что тебе интересно — «хочу что-нибудь про IT», «волонтёрство на осенних каникулах», «мне 15, ищу олимпиаду».
• Скажи «составь план» — распишу подготовку по шагам и напомню о дедлайнах.

Команды:
/plan — твой текущий план подготовки
/link — привязать аккаунт Teenage Space
/reset — забыть наш разговор и начать заново
/help — это сообщение"""


def system_prompt(today: str, availability: str = "") -> str:
    """The agent's system message.

    The category and theme *vocabularies* used to be enumerated here; they now live only
    in the search_events tool schema, which is where the model actually needs them. What
    replaces them is more useful per token: how many open events each category holds
    right now, so an empty one costs no search at all.
    """
    return SYSTEM_PROMPT.format(
        today=today,
        availability=availability or "неизвестно, уточни поиском",
    )
